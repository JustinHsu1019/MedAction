"""
raw_data_transfer.py

[Purpose]
Convert a CSV of raw PMC article text into per-case structured JSON files.

[Input]
- pmc_raw_text.csv
  Each row has two columns: CASE_ID and RAW_TEXT.

[Output]
- output_cases/{CASE_ID}.json
  Each case contains the following fields:
    id, raw_case            -- read directly from the CSV
    generate_case           -- generated by GPT-4o (Prompt 2), containing:
        case_summary
        differential_diagnosis
        final_diagnosis
        diagnosis_results
    gt_info_split           -- parsed from the "Ancillary Tests" section of
                               case_summary, structured as
                               [{type, test_name, info_required}, ...]

[Usage]
  # Process all rows
  python3 raw_data_transfer.py

  # Process only the first N rows (for testing)
  python3 raw_data_transfer.py --n 3

[Notes]
- Already-generated JSON files are skipped automatically (resumable).
- SSL verification is disabled (ssl=False) for macOS; adjust as needed in
  other environments.
- Set the OPENAI_API_KEY environment variable before running.
"""

import os
import re
import json
import asyncio
import argparse
import aiohttp
import pandas as pd
import nest_asyncio

nest_asyncio.apply()

# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------

OPENAI_KEY   = os.environ.get("OPENAI_API_KEY", "")

OPENAI_URL   = "https://api.openai.com/v1/chat/completions"
OPENAI_MODEL = "gpt-4o-2024-11-20"
CONCURRENCY  = 10

INPUT_CSV   = os.path.join(os.path.dirname(__file__), "pmc_raw_text.csv")
OUTPUT_DIR  = os.path.join(os.path.dirname(__file__), "output_cases")

# ---------------------------------------------------------------------------
# Prompt 2
# ---------------------------------------------------------------------------

PROMPT2_SYSTEM = "You are an experienced physician."

PROMPT2_USER = """\
You will receive a patient case report focused on diagnosis. Your task is to:
- Summarize the key information of the patient for diagnosis.
- Summarize the differential diagnosis process, including the rationale for each step and the reasons for considering or excluding specific diagnoses.
- Summarize the final diagnosis of the patient.

Ensure that your summaries are concise and accurate, based solely on the information provided in the case report. Please avoid referencing any images, tables, or other visual data (if any), as that data is no longer accessible.

If the case report is incomplete or does not meet the requirements for summarization, simply output:
"I can't."

Format to follow:

### Case Summary
Please provide a detailed medical history of the patient, including chief complaint, history of present illness, past medical history, family history, physical examination, results of ancillary tests, and other necessary information for the final diagnosis in the following format.
- Patient Information:
- Chief Complaint: If none, write "None."
- History of Present Illness: If none, write "None."
- Past Medical History: If none, write "None."
- Personal History: If none, write "None."
- Family History: If none, write "None."
- Physical Examination: If none, write "None."
- Ancillary Tests: If none, write "None."

### Differential Diagnosis Process
- Firstly, based on the patient's chief complaint and clinical information, an initial list of potential diseases should be generated. This list will then be systematically evaluated by comparing each disease with the patient's symptoms, signs, and test results.
- Then the rationale for including or excluding each diagnosis will be explained based on clinical evidence, highlighting the selection of diagnostic tests that help confirm or rule out specific conditions. The process will involve step-by-step exclusion of less likely diagnoses, ultimately leading to the most probable diagnosis, which will be justified by the clinical reasoning and evidence supporting it.

### Final Diagnosis (with explanation details)
Integrate the patient's clinical presentation, test results, and differential diagnosis process to summarize the final diagnosis. Briefly explain the basis for the diagnosis and highlight the key factors supporting this conclusion.

### Diagnosis results
Just output the diagnostic result without any other explanation.

Case report:
{raw_text}
"""

# ---------------------------------------------------------------------------
# Parse-info prompt (gt_info_split)
# ---------------------------------------------------------------------------

PARSE_INFO_SYSTEM = "You are an experienced physician."

PARSE_INFO_USER = """\
# Task Overview
You will receive an output from an auxiliary diagnostic and treatment large model detailing the additional information required for patient diagnosis analysis [Raw Output Text to be Organized]. Your task is to categorize this content into different information requirement categories, and output it in a JSON dictionary format.

# Organization Requirements
1. Clearly categorize the original required information output into different information need categories.
2. Each point should clearly indicate:
- "type": The major category of the test item (e.g., laboratory tests, imaging examinations, medical history inquiries, etc.)
- "test_name":The specific name of the test item (e.g., MRI scan, CT scan, thyroid function test, lump biopsy, etc.)
- "info_required":The specific content or purpose of the requirement (e.g., to rule out malignant tumors, to better observe the tympanic membrane and middle ear structure, to assess retinal function, etc.)
3. Retain all original content, but if multiple checks are for obtaining the same information or have the same purpose, they can be combined into one point, but the "test_name" field should include all these checks.
4. Do not add new required content; all information should originate from the original output [raw output text to be organized].
5. Do not omit any steps.

# Output Requirements
1. The output format must be a valid JSON format without any other content.
2. Output the type of the test item in the "type" field; output the specific name of the test item in the "test_name" field; output the specific content or purpose of the required information in the "info_required" field.

# Output Format
```json
{{
"type": "Major Category of the Test Item",
"test_name": "Specific Name of the Test Item",
"info_required": "Specific Information Required or the Purpose of the Test"
}}
```

Below is the raw output text that needs to be reorganized:

[Raw Output Text to be Organized]
{info_required}"""


def extract_ancillary_tests(case_summary: str) -> str:
    """Pull out the Ancillary Tests bullet from the case_summary text."""
    if "Ancillary Tests:" not in case_summary:
        return ""
    after = case_summary.split("Ancillary Tests:")[-1].strip()
    # Stop at the next "- <Field>:" line (e.g. "- Physical Examination:")
    lines, result = after.splitlines(), []
    for line in lines:
        if result and re.match(r"^-\s+\w[\w\s]*:", line):
            break
        result.append(line)
    return "\n".join(result).strip()


# ---------------------------------------------------------------------------
# GPT-4o call
# ---------------------------------------------------------------------------

async def _openai_call(session, sem, messages, max_tokens=3000):
    headers = {
        "Authorization": f"Bearer {OPENAI_KEY}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": OPENAI_MODEL,
        "messages": messages,
        "temperature": 0.0,
        "max_tokens": max_tokens,
    }
    async with sem:
        for attempt in range(3):
            try:
                async with session.post(
                    OPENAI_URL, headers=headers, json=payload,
                    timeout=aiohttp.ClientTimeout(total=120),
                ) as resp:
                    if resp.status != 200:
                        print(f"  [OpenAI {resp.status}] {(await resp.text())[:200]}")
                        await asyncio.sleep(2 ** attempt)
                        continue
                    data = await resp.json()
                    return data["choices"][0]["message"]["content"].strip()
            except Exception as e:
                print(f"  [attempt {attempt + 1}] {e}")
                await asyncio.sleep(2 ** attempt)
    return None


def parse_gt_info_split(raw_json_text: str) -> list:
    """Parse GPT's JSON output into a list of {type, test_name, info_required} dicts."""
    if not raw_json_text:
        return []
    # Strip markdown code fences if present
    text = re.sub(r"```(?:json)?", "", raw_json_text).strip().rstrip("`").strip()
    try:
        parsed = json.loads(text)
        if isinstance(parsed, dict):
            parsed = [parsed]
        return parsed
    except json.JSONDecodeError:
        print(f"  [WARN] gt_info_split JSON parse failed: {text[:100]}")
        return []

# ---------------------------------------------------------------------------
# Parse GPT-4o response into structured fields
# ---------------------------------------------------------------------------

def parse_gpt_response(text):
    """Extract the four sections from Prompt 2 output."""
    if not text or text.strip().lower().startswith("i can't"):
        return None

    sections = {
        "case_summary":            "",
        "differential_diagnosis":  "",
        "final_diagnosis":         "",
        "diagnosis_results":       "",
    }

    headers = [
        (r"### Case Summary",                    "case_summary"),
        (r"### Differential Diagnosis Process",  "differential_diagnosis"),
        (r"### Final Diagnosis",                 "final_diagnosis"),
        (r"### Diagnosis [Rr]esults",            "diagnosis_results"),
    ]

    for i, (pattern, key) in enumerate(headers):
        m = re.search(pattern, text, re.IGNORECASE)
        if not m:
            continue
        after = text[m.end():]
        # Cut at next section header
        for next_pattern, _ in headers[i + 1:]:
            m2 = re.search(next_pattern, after, re.IGNORECASE)
            if m2:
                after = after[:m2.start()]
        sections[key] = after.strip()

    return sections

# ---------------------------------------------------------------------------
# Process one case
# ---------------------------------------------------------------------------

async def process_case(row, session, sem):
    case_id  = str(row["CASE_ID"]).strip()
    raw_text = str(row["RAW_TEXT"]).strip()

    out_path = os.path.join(OUTPUT_DIR, f"{case_id}.json")
    if os.path.exists(out_path):
        print(f"  [skip] {case_id} already exists")
        return

    print(f"  Processing {case_id} ...")

    # --- Step 1: Prompt 2 → generate_case ---
    prompt2_messages = [
        {"role": "system", "content": PROMPT2_SYSTEM},
        {"role": "user",   "content": PROMPT2_USER.format(raw_text=raw_text)},
    ]
    gpt_output = await _openai_call(session, sem, prompt2_messages, max_tokens=3000)

    if gpt_output is None:
        print(f"  [ERROR] {case_id}: GPT call failed (Prompt 2)")
        return

    generate_case = parse_gpt_response(gpt_output)
    if generate_case is None:
        print(f"  [SKIP] {case_id}: model said I can't or parse failed")
        return

    # --- Step 2: parse_info_requirements → gt_info_split ---
    ancillary_tests = extract_ancillary_tests(generate_case["case_summary"])
    gt_info_split = []
    if ancillary_tests and ancillary_tests.lower() != "none.":
        parse_messages = [
            {"role": "system", "content": PARSE_INFO_SYSTEM},
            {"role": "user",   "content": PARSE_INFO_USER.format(info_required=ancillary_tests)},
        ]
        parse_output = await _openai_call(session, sem, parse_messages, max_tokens=2000)
        gt_info_split = parse_gt_info_split(parse_output)

    result = {
        "id":            case_id,
        "raw_case":      raw_text,
        "generate_case": generate_case,
        "gt_info_split": gt_info_split,
    }

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=4)

    print(f"  [OK] {case_id} saved")

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

async def main(n: int | None):
    df = pd.read_csv(INPUT_CSV)
    print(f"Loaded {len(df)} rows from CSV")

    if n is not None:
        df = df.iloc[:n]
        print(f"Running on first {n} row(s)")

    sem       = asyncio.Semaphore(CONCURRENCY)
    # macOS (Big Sur) setting: ssl=False avoids SSL-related errors; adjust as needed in other environments
    connector = aiohttp.TCPConnector(limit=CONCURRENCY + 5, ssl=False)

    async with aiohttp.ClientSession(connector=connector) as session:
        tasks = [process_case(row, session, sem) for _, row in df.iterrows()]
        await asyncio.gather(*tasks)

    print("Done.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--n", type=int, default=None, help="Number of rows to process (default: all)")
    args = parser.parse_args()
    asyncio.run(main(args.n))